import assert from 'node:assert/strict';
import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { test } from 'node:test';
import yaml from 'js-yaml';
import { installGems } from '../../src/cli/commands/gems-install.js';
import { version } from '../../src/version.js';
import { withSandbox } from '../helpers/sandbox.js';

const configPath = '_gems/_config/project-config.yaml';
const manifestPath = '_gems/_config/manifest.yaml';
const orchestratorPath = '_gems/core/agents/gems-orchestrator.md';
const specialists = {
  diagnose: 'source-analyst',
  plan: 'migration-planner',
  implement: 'engine-specialist',
  verify: 'equivalence-verifier'
};

test('installs all GEMS agents and preserves destination files on reinstall', async () => {
  await withSandbox(async ({ path }) => {
    const read = file => readFile(join(path, file), 'utf8');
    const write = (file, contents) => writeFile(join(path, file), contents);
    const project = '{"FileVersion": 3}\n';
    const instructions = '# Project instructions\n\nUse the existing asset naming conventions.\n';
    const customAgent = 'name = "custom-agent"\n';

    await mkdir(join(path, '.codex', 'agents'), { recursive: true });
    await write('Sample.uproject', project);
    await write('AGENTS.md', instructions);
    await write('.gitignore', 'Build/\n');
    await write('.codex/agents/custom-agent.toml', customAgent);

    await installGems({ yes: true }, path);

    const config = yaml.load(await read(configPath));
    const manifest = yaml.load(await read(manifestPath));
    const orchestrator = await read(orchestratorPath);
    const compiledAgents = [orchestrator];
    assert.equal(config.target_engine, 'unreal-5');
    assert.equal(config.settings.ide, 'codex');
    assert.equal(config.settings.output_folder, '_gems-output');
    assert.match(config.runtime.entry, /[/\\]bin[/\\]gems\.js$/);
    assert.deepEqual(config.modules.installed, ['core', 'migration']);
    assert.deepEqual(manifest.modules.installed, config.modules.installed);
    assert.equal(manifest.gems_version, version);
    assert.equal(manifest.project.target_engine, config.target_engine);
    assert.deepEqual(yaml.load(await read('_gems/core/module.yaml')).agents, ['gems-orchestrator']);
    for (const command of ['init', 'status', 'approve', 'resume', ...Object.keys(specialists)]) {
      assert.ok(orchestrator.includes(`### \`*${command}\``), `Missing action for *${command}`);
    }
    assert.ok(orchestrator.includes('Generated by GEMS Agent Compiler'));
    assert.ok(!orchestrator.includes('gd-ks state context'));
    const nativeAgentPath = '.codex/agents/gems-orchestrator.toml';
    const nativeAgent = await read(nativeAgentPath);
    assert.ok(nativeAgent.includes(orchestratorPath));
    assert.deepEqual(await readdir(join(path, '_gems', 'core', 'agents')).then(files => files.sort()), [
      'gems-orchestrator.agent.yaml', 'gems-orchestrator.md'
    ]);
    const module = yaml.load(await read('_gems/migration/module.yaml'));
    assert.deepEqual(module.agents, Object.values(specialists));
    assert.deepEqual(module.workflows, ['diagnosis', 'planning', 'implementation', 'verification']);
    for (const name of module.workflows) {
      const root = `_gems/migration/workflows/${name}`;
      assert.equal(yaml.load(await read(`${root}/workflow.yaml`)).name, name);
      assert.ok((await read(`${root}/instructions.md`)).includes('gems advance'));
    }
    const { menu } = yaml.load(await read(orchestratorPath.replace('.md', '.agent.yaml')));
    for (const [command, id] of Object.entries(specialists)) {
      const agentPath = `_gems/migration/agents/${id}.md`;
      const specialist = yaml.load(await read(agentPath.replace('.md', '.agent.yaml')));
      const route = menu.find(({ trigger }) => trigger === command);
      assert.equal(route?.delegate_to, agentPath);
      assert.ok(orchestrator.includes(`\`*${command}\` → \`${agentPath}\``));
      assert.equal(specialist.metadata.id, agentPath);
      assert.ok(specialist.menu.some(({ trigger, action }) => trigger === command && action === `#${command}`));
      assert.ok(specialist.actions[command].trim());
      const compiled = await read(agentPath);
      assert.ok(compiled.includes(`### \`*${command}\``));
      compiledAgents.push(compiled);
      const nativeSpecialist = await read(`.codex/agents/gems-${id}.toml`);
      assert.ok(nativeSpecialist.includes(`name = "gems-${id}"`));
      assert.ok(nativeSpecialist.includes(agentPath));
    }
    for (const compiled of compiledAgents) {
      assert.ok(compiled.includes('## Asking for User Input'));
      for (const tool of ['request_user_input', 'request_user_input_async', 'AskUserQuestion']) {
        assert.ok(compiled.includes(`\`${tool}\``));
      }
      assert.ok(compiled.includes('Use a numbered list in chat'));
      assert.ok(compiled.includes('Approval requires an explicit answer'));
    }
    for (const id of ['godot-4', 'unity-6', 'unreal-5']) {
      const profile = yaml.load(await read(`_gems/migration/engine-profiles/${id}.yaml`));
      assert.equal(profile.engine.id, id);
      assert.ok(profile.paradigms && profile.capabilities);
    }

    config.settings.communication_language = 'pt-BR';
    await write(configPath, yaml.dump(config));
    await write('_gems-output/migration-setup.md', '# Saved setup\n');
    const customizedNativeAgent = `${nativeAgent}# Local customization\n`;
    await write(nativeAgentPath, customizedNativeAgent);
    await installGems({ yes: true }, path);

    const updatedInstructions = await read('AGENTS.md');
    assert.ok(updatedInstructions.startsWith(instructions));
    assert.equal(updatedInstructions.match(/<!-- gems:instructions:start -->/g)?.length, 1);
    assert.ok(updatedInstructions.includes('delegate_to'));
    assert.ok(updatedInstructions.includes('`request_user_input` or `request_user_input_async`'));
    assert.equal(await read('Sample.uproject'), project);
    assert.equal(await read('.gitignore'), 'Build/\n');
    assert.equal(await read('.codex/agents/custom-agent.toml'), customAgent);
    assert.equal(await read(nativeAgentPath), customizedNativeAgent);
    assert.equal(await read('_gems-output/migration-setup.md'), '# Saved setup\n');
    assert.equal(yaml.load(await read(configPath)).settings.communication_language, 'pt-BR');
    assert.equal(yaml.load(await read(manifestPath)).installed_at, manifest.installed_at);
    assert.ok(!(await readdir(path)).includes('_gdks'));
  }, 'gems-install');
});

test('can install for manual agent loading and reuses the saved integration choice', async () => {
  await withSandbox(async ({ path }) => {
    await writeFile(join(path, 'project.godot'), 'config_version=5\n');
    await installGems({ yes: true, ide: 'none' }, path);
    await installGems({ yes: true }, path);

    const config = yaml.load(await readFile(join(path, configPath), 'utf8'));
    assert.equal(config.target_engine, 'godot-4');
    assert.equal(config.settings.ide, 'none');
    assert.deepEqual((await readdir(path)).sort(), ['_gems', '_gems-output', 'project.godot']);
    assert.equal((await readdir(join(path, '_gems/migration/agents'))).length, 8);
  }, 'gems-manual');
});

test('rejects an engine that conflicts with the destination before installing', async () => {
  await withSandbox(async ({ path }) => {
    await writeFile(join(path, 'project.godot'), 'config_version=5\n');
    await assert.rejects(installGems({ yes: true, engine: 'unreal-5' }, path), /matches godot-4/);
    assert.deepEqual(await readdir(path), ['project.godot']);
  }, 'gems-engine-conflict');
});
